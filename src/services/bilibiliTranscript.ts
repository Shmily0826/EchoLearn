import type { TranscriptLine, BiliPart } from '../types';
import { fetchWithTimeout, VPS_API_URL } from '../utils/resilientFetch';

/**
 * Bilibili transcript fetcher.
 *
 * Uses the same server-side path as YouTube: Cloudflare Worker -> AWS VPS yt-dlp.
 * yt-dlp natively supports Bilibili, so this avoids the previously hardcoded
 * dependency on the local `proxy.echo-learn.uk` Cloudflare Tunnel (which is
 * frequently offline) and also removes CORS issues.
 *
 * Resilience: the Worker can intermittently hang from some mobile networks, so
 * we fall back to the VPS directly if the Worker fails.
 */

const CF_WORKER_URL = 'https://yt-transcript-proxy.rng2018520.workers.dev';

interface TranscriptFetchResult {
  lines: TranscriptLine[];
  language: string;
  isAutoGenerated: boolean;
  /** Set to "asr" when the transcript was produced by Whisper on the VPS (no native subtitles). */
  source?: 'asr' | 'vps' | string;
}

async function fetchBilibiliFromWorker(
  bvid: string,
  lang: string,
  part?: number,
): Promise<Response> {
  const qs = `bvid=${encodeURIComponent(
    bvid,
  )}&lang=${encodeURIComponent(lang)}${part ? `&p=${part}` : ''}`;
  return fetchWithTimeout(`${CF_WORKER_URL}/api/bilibili?${qs}`, { timeoutMs: 18000 });
}

async function fetchBilibiliFromVps(
  bvid: string,
  lang: string,
  part?: number,
): Promise<Response> {
  let url = `https://www.bilibili.com/video/${encodeURIComponent(bvid)}`;
  if (part) url += `?p=${encodeURIComponent(part)}`;
  const vpsUrl = `${VPS_API_URL}/api/transcript?${new URLSearchParams({ url, lang })}`;
  return fetchWithTimeout(vpsUrl, { timeoutMs: 35000 });
}

/**
 * Fetch transcript/subtitles for a Bilibili video.
 *
 * Tries the CF Worker first; if it hangs/fails, falls back to the VPS directly.
 *
 * @param bvid Bilibili video ID (e.g. "BV1GJ411x7hT")
 * @param lang Preferred subtitle language (default: "zh-CN")
 * @param part Optional 1-based part number for multi-part (分p) videos
 */
export async function fetchBilibiliTranscript(
  bvid: string,
  lang: string = 'zh-CN',
  part?: number,
): Promise<TranscriptFetchResult> {
  let resp: Response;
  try {
    resp = await fetchBilibiliFromWorker(bvid, lang, part);
    if (!resp.ok) {
      const detail = await resp.clone().text().catch(() => '');
      console.warn(`[EchoLearn] Bilibili Worker error: ${resp.status} ${detail.slice(0, 200)}`);
      throw new Error('Worker failed');
    }
  } catch (err) {
    console.warn('[EchoLearn] Bilibili Worker path failed, trying VPS directly:', err instanceof Error ? err.message : err);
    resp = await fetchBilibiliFromVps(bvid, lang, part);
  }

  const body = await resp.text().catch(() => '');

  if (!resp.ok) {
    throw new Error(
      `Bilibili transcript error: ${resp.status} ${body.slice(0, 200)}`,
    );
  }

  const data = JSON.parse(body) as TranscriptFetchResult;
  if (!data.lines || data.lines.length === 0) {
    throw new Error(
      'No transcript available for this Bilibili video. ' +
        'It may have neither CC subtitles nor extractable audio. ' +
        'You can import a transcript manually.',
    );
  }

  // Mark the source so the UI can tell the user we fell back to the VPS.
  if (!resp.url.startsWith(CF_WORKER_URL)) {
    data.source = data.source || 'vps';
  }
  return data;
}

/**
 * Fetch video title and uploader from Bilibili.
 */
export async function getBilibiliVideoTitle(
  bvid: string,
  part?: number,
): Promise<{ title: string; ownerName: string; partCount?: number; parts?: BiliPart[] } | null> {
  try {
    const url = `${CF_WORKER_URL}/api/bilibili?bvid=${encodeURIComponent(
      bvid,
    )}&info=1${part ? `&p=${part}` : ''}`;
    const resp = await fetch(url);
    if (!resp.ok) return null;

    const data = (await resp.json()) as {
      title?: string;
      ownerName?: string;
      partCount?: number;
      parts?: BiliPart[];
    };
    return {
      title: data.title || '',
      ownerName: data.ownerName || '',
      partCount: data.partCount,
      parts: data.parts,
    };
  } catch {
    return null;
  }
}

/**
 * Resolve a Bilibili URL (including a b23.tv short link) to its metadata via the
 * VPS directly. The VPS runs yt-dlp, which resolves b23.tv redirects and returns
 * the canonical BV id, title, and (for multi-part videos) the part list.
 *
 * This is the only way to recover a BV id from a b23.tv short code on the client,
 * because the redirect target is cross-origin and unreadable from the browser.
 */
export async function getBilibiliMetaByUrl(
  fullUrl: string,
): Promise<{ title: string; ownerName: string; bvid?: string; partCount?: number; parts?: BiliPart[] } | null> {
  try {
    const vpsUrl = `${VPS_API_URL}/api/info?${new URLSearchParams({ url: fullUrl })}`;
    const resp = await fetchWithTimeout(vpsUrl, { timeoutMs: 30000 });
    if (!resp.ok) return null;
    const data = (await resp.json()) as {
      title?: string;
      ownerName?: string;
      bvid?: string;
      partCount?: number;
      parts?: BiliPart[];
    };
    return {
      title: data.title || '',
      ownerName: data.ownerName || '',
      bvid: data.bvid || undefined,
      partCount: data.partCount,
      parts: data.parts,
    };
  } catch {
    return null;
  }
}
