def _multipart(fields: dict, filename: str, blob: bytes, content_type: str):
    """Minimal multipart/form-data encoder.

    Hand-rolled so the service keeps its three-package dependency list and can
    be redeployed by copying a single file — no pip install on the VPS.
    """
    boundary = "----EchoLearn" + uuid.uuid4().hex
    body = bytearray()
    for key, value in fields.items():
        body += f"--{boundary}\r\n".encode()
        body += f'Content-Disposition: form-data; name="{key}"\r\n\r\n'.encode()
        body += f"{value}\r\n".encode()
    body += f"--{boundary}\r\n".encode()
    body += (
        f'Content-Disposition: form-data; name="file"; filename="{filename}"\r\n'
    ).encode()
    body += f"Content-Type: {content_type}\r\n\r\n".encode()
    body += blob
    body += b"\r\n"
    body += f"--{boundary}--\r\n".encode()
    return bytes(body), f"multipart/form-data; boundary={boundary}"


def _download_audio(target_url: str, td: str, part: Optional[int] = None) -> Optional[str]:
    """Grab the audio track and transcode to 16 kHz mono mp3 (Whisper's native
    sample rate — anything richer just inflates the upload)."""
    cmd = [
        sys.executable,
        "-m",
        "yt_dlp",
        "--js-runtimes",
        "node",
        "--remote-components",
        "ejs:github",
        "-f",
        "bestaudio/best",
        "--extract-audio",
        "--audio-format",
        "mp3",
        "--postprocessor-args",
        "ffmpeg:-ar 16000 -ac 1 -b:a 32k",
        "--retries",
        "3",
        "--fragment-retries",
        "3",
        *_playlist_flag(part),
        "--quiet",
        "--no-warnings",
        "--no-overwrites",
        "-o",
        os.path.join(td, "audio.%(ext)s"),
        target_url,
    ]
    cmd += _site_args(target_url)
    # YouTube: try NO proxy first (TVHTML5 bypasses the datacenter bot-check),
    # then fall back to the residential proxy only if the direct attempt fails.
    envs = [_no_proxy_env()]
    if YTDLP_PROXY and _is_youtube(target_url):
        envs.append(_proxy_env(target_url))

    for env in envs:
        for attempt in range(1, YTDLP_RETRIES + 1):
            # Clear any partial download from a previous flaky attempt so the
            # --no-overwrites flag doesn't skip because of a broken fragment.
            for fname in os.listdir(td):
                try:
                    os.remove(os.path.join(td, fname))
                except OSError:
                    pass
            try:
                subprocess.run(
                    cmd, cwd=td, capture_output=True, text=True,
                    timeout=YTDLP_TIMEOUT, env=env,
                )
            except subprocess.TimeoutExpired:
                return None
            for fname in sorted(os.listdir(td)):
                if fname.endswith(".mp3"):
                    return os.path.join(td, fname)
    return None


def _audio_cache_path(target_url: str, part: Optional[int]) -> str:
    """Stable cache filename for a (url, part) pair.

    Bilibili share URLs often carry tracking params (spm_id_from, vd_source,
    etc.) that would otherwise fragment the cache. Normalize before hashing.
    """
    normalized = _normalize_bilibili_url(target_url)
    key = f"{normalized}|p={part}"
    digest = hashlib.md5(key.encode("utf-8")).hexdigest()
    return os.path.join(AUDIO_CACHE_DIR, f"{digest}.mp3")


def _audio_duration(path: str) -> float:
    """Return audio duration in seconds via ffprobe, or 0.0 on failure."""
    try:
        proc = subprocess.run(
            [
                "ffprobe", "-v", "error",
                "-show_entries", "format=duration",
                "-of", "default=noprint_wrappers=1:nokey=1",
                path,
            ],
            capture_output=True, text=True, timeout=30,
        )
        val = proc.stdout.strip()
        return float(val) if val else 0.0
    except (subprocess.TimeoutExpired, ValueError, OSError):
        return 0.0


def _audio_meta_path(out_path: str) -> str:
    return out_path + ".meta.json"


def _write_audio_meta(out_path: str, expected: int) -> None:
    """Persist the real (expected) duration next to the cached mp3 so a later
    read can detect a truncated download without re-fetching metadata."""
    try:
        with open(_audio_meta_path(out_path), "w", encoding="utf-8") as fh:
            json.dump({"expected": expected, "duration": _audio_duration(out_path)}, fh)
    except OSError:
        pass


def _cache_valid(out_path: str) -> bool:
    """True if the cached mp3 exists and isn't a clearly truncated partial.

    A legacy cache written before sidecar metadata exists is trusted as-is.
    """
    if not (os.path.exists(out_path) and os.path.getsize(out_path) > 0):
        return False
    meta_path = _audio_meta_path(out_path)
    if not os.path.exists(meta_path):
        return True
    try:
        with open(meta_path, encoding="utf-8") as fh:
            meta = json.load(fh)
        expected = int(meta.get("expected") or 0)
    except (OSError, json.JSONDecodeError):
        return True
    if expected:
        dur = _audio_duration(out_path)
        if dur and dur < expected * 0.5:
            return False
    return True


def _extract_playback_audio(target_url: str, part: Optional[int] = None) -> Optional[str]:
    """Download the audio track at a *listenable* bitrate and cache it on disk.

    Unlike _download_audio (which targets Whisper at 16 kHz/32 kbps), this keeps
    44.1 kHz mono at 64 kbps — plenty for speech, and ~¼ the size of 128k stereo
    so cold extraction through the flaky proxy is faster.
    Returns the cached .mp3 path, or None on failure.

    The residential proxy is flaky and can drop mid-download, leaving a truncated
    mp3 that still "exists" on disk. We guard against that with a duration check
    (re-extract any file clearly shorter than the real video) and by retrying the
    whole download with exponential backoff — a fresh proxy IP (rotating
    residential) often completes what the previous attempt dropped. The per-attempt
    subprocess timeout is kept well under the Cloudflare Worker's 180s budget so a
    failed attempt fails fast instead of burning the whole window.
    """
    out_path = _audio_cache_path(target_url, part)

    def _expected_duration() -> int:
        # Tight metadata budget: fail fast rather than burning the whole
        # extraction window on a flaky proxy watch-page fetch. A miss just
        # disables the truncation check below (still returns the file).
        try:
            return int(_fetch_meta(target_url, part, attempts=2, timeout=45).get("duration") or 0)
        except Exception:
            return 0

    if _cache_valid(out_path):
        return out_path

    expected = _expected_duration()

    # Hard wall-clock ceiling so we never exceed the Worker's 180s and 502
    # purely because the VPS was still working. Leave a margin for the Worker
    # to stream the result back.
    deadline = time.time() + AUDIO_OVERALL_TIMEOUT

    cmd = [
        sys.executable,
        "-m",
        "yt_dlp",
        "--js-runtimes",
        "node",
        "--remote-components",
        "ejs:github",
        "-f",
        "bestaudio/best",
        "--extract-audio",
        "--audio-format",
        "mp3",
        "--postprocessor-args",
        "ffmpeg:-ar 44100 -ac 1 -b:a 64k",
        "--retries",
        str(YTDLP_RETRIES),
        "--fragment-retries",
        str(YTDLP_RETRIES),
        *_playlist_flag(part),
        "--quiet",
        "--no-warnings",
        "-o",
        out_path,
        target_url,
    ]
    cmd += _site_args(target_url)

    backoff = 5  # seconds before the 2nd attempt; grows if more attempts allowed
    # YouTube: try NO proxy first (TVHTML5 bypasses the datacenter bot-check),
    # then alternate to the residential proxy on later attempts. Bilibili never
    # reaches here (the /api/audio route uses the API-direct path above).
    envs = [_no_proxy_env()]
    if YTDLP_PROXY and _is_youtube(target_url):
        envs.append(_proxy_env(target_url))
    for attempt in range(1, AUDIO_MAX_ATTEMPTS + 1):
        # Don't start an attempt we can't finish before the deadline — bail so
        # the frontend can auto-retry instead of us overrunning the Worker window.
        if time.time() + AUDIO_DL_TIMEOUT > deadline:
            break
        # Clear any partial file so a fresh attempt isn't skipped.
        try:
            if os.path.exists(out_path):
                os.remove(out_path)
        except OSError:
            pass
        try:
            subprocess.run(
                cmd, cwd=AUDIO_CACHE_DIR, capture_output=True, text=True,
                timeout=AUDIO_DL_TIMEOUT, env=envs[(attempt - 1) % len(envs)],
            )
        except subprocess.TimeoutExpired:
            # Don't burn the whole Worker budget on one hung attempt; let the
            # backoff + next attempt (fresh proxy IP) take a shot.
            pass
        if not (os.path.exists(out_path) and os.path.getsize(out_path) > 0):
            if attempt < AUDIO_MAX_ATTEMPTS:
                time.sleep(backoff)
                backoff = min(backoff * 2, 20)
            continue
        # Reject clearly truncated downloads (proxy dropped mid-stream).
        if expected:
            dur = _audio_duration(out_path)
            if dur and dur < expected * 0.5:
                try:
                    os.remove(out_path)
                except OSError:
                    pass
                if attempt < AUDIO_MAX_ATTEMPTS:
                    time.sleep(backoff)
                    backoff = min(backoff * 2, 20)
                continue
        _write_audio_meta(out_path, expected)
        return out_path
    return None


# Serialize concurrent extractions of the same audio so two requests (e.g. the
# background pre-warm fetch and the audio player's own fetch) don't spawn two
# yt-dlp processes that fight the flaky proxy — the second waits for the first.
_audio_inflight_lock = threading.Lock()
_audio_inflight: "dict[str, threading.Event]" = {}


def _extract_playback_audio_dedup(target_url: str, part: Optional[int]) -> Optional[str]:
    """Like _extract_playback_audio, but concurrent calls for the same url+part
    share a single extraction. The first caller does the work; later callers wait
    on an event and then read the resulting cache file."""
    key = _audio_cache_path(target_url, part)
    # Fast path: already cached (possibly by another in-flight request).
    if _cache_valid(key):
        return key
    with _audio_inflight_lock:
        ev = _audio_inflight.get(key)
        if ev is not None:
            # Another request is extracting this exact url+part; wait for it.
            ev.wait(timeout=AUDIO_OVERALL_TIMEOUT + 60)
            if _cache_valid(key):
                return key
            # The other attempt failed; fall through and try ourselves.
        ev = threading.Event()
        _audio_inflight[key] = ev
    try:
        return _extract_playback_audio(target_url, part)
    finally:
        with _audio_inflight_lock:
            _audio_inflight.pop(key, None)
            ev.set()


def _groq_transcribe(path: str) -> dict:
    """Send one audio file to Groq Whisper and return the EchoLearn payload.

    The language is deliberately auto-detected rather than hinted: the point of
    ASR on Bilibili is the English-language content hosted there, and pinning
    the hint to zh would wreck exactly those videos.
    """
    with open(path, "rb") as fh:
        blob = fh.read()

    if len(blob) > GROQ_MAX_BYTES:
        raise HTTPException(
            status_code=413,
            detail=f"Audio is {len(blob) // 1024 // 1024} MB, over the 25 MB Groq limit",
        )

    body, content_type = _multipart(
        {"model": GROQ_MODEL, "response_format": "verbose_json"},
        "audio.mp3",
        blob,
        "audio/mpeg",
    )
    req = urllib.request.Request(
        GROQ_ENDPOINT,
        data=body,
        headers={
            "Authorization": f"Bearer {GROQ_API_KEY}",
            "Content-Type": content_type,
            # Groq sits behind Cloudflare, which bans the default
            # "Python-urllib/3.x" UA with HTTP 403 / error 1010. Send a
            # non-default UA so the request is accepted.
            "User-Agent": "EchoLearn-VPS/1.0 (groq-asr)",
        },
        method="POST",
    )

    # Groq works directly from this VPS (verified end-to-end with no proxy),
    # and routing it through the residential proxy only adds a flaky hop
    # (Broken pipe / IncompleteRead). Call it directly and retry a couple of
    # times to absorb Groq's occasional transient 403/abuse throttle on the
    # free tier.
    raw = None
    last_err = ""
    for attempt in range(1, 3):
        try:
            with urllib.request.urlopen(req, timeout=GROQ_TIMEOUT) as resp:
                raw = json.load(resp)
            break
        except urllib.error.HTTPError as exc:
            last_err = exc.read().decode("utf-8", "ignore")[:400]
            # Surface 429 (out of quota) as-is; other HTTP errors may be
            # transient, so retry once.
            if exc.code == 429:
                raise HTTPException(status_code=429, detail=f"Groq HTTP 429: {last_err}")
            if attempt < 2:
                time.sleep(1)
                continue
            status = 502
            raise HTTPException(status_code=status, detail=f"Groq HTTP {exc.code}: {last_err}")
        except Exception as exc:  # noqa: BLE001 - transient network blips
            last_err = str(exc)
            if attempt < 2:
                time.sleep(1)
                continue
            raise HTTPException(status_code=502, detail=f"Groq request failed: {exc}")

    segments = raw.get("segments") or []
    lines = [
        {
            "id": f"yt_{i + 1}",
            "start": round(float(seg.get("start") or 0), 3),
            "end": round(float(seg.get("end") or 0), 3),
            "text": (seg.get("text") or "").strip(),
        }
        for i, seg in enumerate(segments)
        if (seg.get("text") or "").strip()
    ]

    if not lines:
        text = (raw.get("text") or "").strip()
        if not text:
            raise HTTPException(status_code=404, detail="Whisper returned no speech")
        lines = [{"id": "yt_1", "start": 0, "end": 0, "text": text}]

    return {
        "lines": lines,
        "language": raw.get("language") or "unknown",
        "isAutoGenerated": True,
        "source": "asr",
    }


