def _is_youtube(target_url: str) -> bool:
    return "youtube.com" in target_url or "youtu.be" in target_url


def _is_bilibili(target_url: str) -> bool:
    return "bilibili.com" in target_url or "b23.tv" in target_url


def _is_english(language: Optional[str]) -> bool:
    """Whether a subtitle language code denotes English (incl. Bilibili 'ai-en')."""
    l = (language or "").lower()
    return l in ("en", "ai-en") or l.startswith("en")


def _lang_rank(language: Optional[str]) -> int:
    """Sort rank for subtitle language: English first, then Chinese, then rest."""
    l = (language or "").lower()
    if l in ("en", "ai-en") or l.startswith("en"):
        return 0
    if l.startswith("zh") or l == "ai-zh":
        return 1
    return 2


def _extract_bvid(target_url: str):
    """Pull the BV id out of a Bilibili URL (or return None)."""
    m = re.search(r"(BV[0-9A-Za-z]+)", target_url)
    return m.group(1) if m else None


def _bilibili_parts(bvid: str):
    """Return the part list for a Bilibili video via its public view API.

    The view API (api.bilibili.com/x/web-interface/view) answers the VPS
    datacenter IP fine — only the *watch page* returns HTTP 412 — so no
    proxy is needed. Returns {"partCount": N, "parts": [{"index", "title"}]}
    or None on any failure (the caller then simply skips the part picker).
    """
    api = f"https://api.bilibili.com/x/web-interface/view?bvid={bvid}"
    req = urllib.request.Request(
        api,
        headers={
            "User-Agent": (
                "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
                "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
            ),
            "Referer": "https://www.bilibili.com/",
        },
    )
    try:
        with urllib.request.urlopen(req, timeout=10) as resp:
            data = json.loads(resp.read().decode("utf-8", "ignore"))
    except Exception:
        return None
    if data.get("code") != 0:
        return None
    pages = (data.get("data") or {}).get("pages") or []
    parts = [{"index": p.get("page"), "title": p.get("part") or ""} for p in pages]
    return {"partCount": len(parts), "parts": parts}


def _host_allowed(target_url: str) -> bool:
    """Only let known hosts through so the endpoint can't be used as an
    open yt-dlp relay for arbitrary sites."""
    if not target_url.startswith(("http://", "https://")):
        return False
    return any(h in target_url for h in _ALLOWED_HOSTS)


def _site_args(target_url: str) -> list:
    """Per-site yt-dlp flags.

    - The residential proxy is applied to YouTube and Bilibili (Bilibili's watch
      page returns HTTP 412 from datacenter IPs).
    - Cookies (YTDLP_COOKIES, e.g. a Bilibili SESSDATA jar) are applied whenever
      the file exists. Bilibili only exposes subtitle tracks to logged-in
      sessions, so the cookie is what unlocks real subtitles there — without it
      the transcript route falls through to ASR.
    """
    args: list = []
    if YTDLP_PROXY and (_is_youtube(target_url) or _is_bilibili(target_url)):
        args += ["--proxy", YTDLP_PROXY]
    if YTDLP_COOKIES and os.path.exists(YTDLP_COOKIES):
        args += ["--cookies", YTDLP_COOKIES]
    return args

# ── In-memory TTL cache (keyed by video_id:lang) ──────────────
# Protects the single VPS IP from repeat YouTube hits on popular videos and
# speeds up repeated fetches of the same video+lang. Only successful results
# are cached; failures are always retried.
_CACHE: "OrderedDict[str, tuple[float, dict]]" = OrderedDict()
_CACHE_MAX = 2000


def _cache_get(video_id: str, lang: str):
    key = f"{video_id}:{lang}"
    item = _CACHE.get(key)
    if item is None:
        return None
    expiry, payload = item
    if expiry < time.time():
        _CACHE.pop(key, None)
        return None
    _CACHE.move_to_end(key)  # LRU touch
    return payload


def _cache_put(video_id: str, lang: str, payload: dict):
    key = f"{video_id}:{lang}"
    _CACHE[key] = (time.time() + YTDLP_CACHE_TTL, payload)
    _CACHE.move_to_end(key)
    if len(_CACHE) > _CACHE_MAX:
        _CACHE.popitem(last=False)  # evict oldest


# ── Parsers ───────────────────────────────────────────────────────

def _parse_json3(raw: dict) -> list:
    events = raw.get("events", []) if isinstance(raw, dict) else []
    lines = []
    idx = 0
    for ev in events:
        segs = ev.get("segs") or []
        text = "".join(s.get("utf8", "") for s in segs).strip()
        if not text:
            continue
        start = (ev.get("tStartMs") or 0) / 1000.0
        dur = ev.get("dDurationMs") or 0
        lines.append(
            {
                "id": f"yt_{idx + 1}",
                "start": round(start, 3),
                "end": round(start + dur / 1000.0, 3),
                "text": text,
            }
        )
        idx += 1
    return lines


def _parse_vtt(text: str) -> list:
    # Strip WEBVTT header and any NOTE blocks.
    lines = []
    idx = 0
    # Split into cues by blank lines.
    blocks = re.split(r"\n\s*\n", text)
    cue_re = re.compile(
        r"(\d{1,2}:)?\d{1,2}:\d{2}\.\d{1,3}\s*-->\s*(\d{1,2}:)?\d{1,2}:\d{2}\.\d{1,3}"
    )
    for block in blocks:
        block = block.strip()
        if not block or block.startswith("WEBVTT") or block.startswith("NOTE"):
            continue
        parts = block.split("\n")
        # First line may be a cue index or the timestamp; find the timestamp line.
        ts_line = None
        text_lines = []
        for line in parts:
            if cue_re.search(line):
                ts_line = line
            elif not line.strip().isdigit() or ts_line is None:
                text_lines.append(line)
        if not ts_line:
            continue
        m = cue_re.search(ts_line)
        start_str, end_str = m.group(0).split("-->")
        start = _vtt_time_to_sec(start_str.strip())
        end = _vtt_time_to_sec(end_str.strip())
        text = " ".join(text_lines).strip()
        # Strip inline tags like <c>, <i>, <00:00:00.000>
        text = re.sub(r"<[^>]+>", "", text).strip()
        if not text:
            continue
        lines.append(
            {
                "id": f"yt_{idx + 1}",
                "start": round(start, 3),
                "end": round(end, 3),
                "text": text,
            }
        )
        idx += 1
    return lines


def _vtt_time_to_sec(s: str) -> float:
    s = s.strip()
    # Formats: HH:MM:SS.mmm or MM:SS.mmm
    parts = s.split(":")
    parts = [float(p) for p in parts]
    if len(parts) == 3:
        h, m, sec = parts
    else:
        h, m, sec = 0, parts[0], parts[1]
    return h * 3600 + m * 60 + sec


def _read_subtitle_file(td: str):
    """Return (lines, language, is_auto) for the best usable subtitle file.

    Hand-written subtitles are preferred over auto-generated ones; this matters
    most for Bilibili, where real tracks (when present) are far cleaner than the
    auto captions.
    """
    parsed = []
    for fname in sorted(os.listdir(td)):
        path = os.path.join(td, fname)
        if fname.endswith(".json3"):
            try:
                with open(path, "r", encoding="utf-8") as fh:
                    raw = json.load(fh)
            except Exception:
                continue
            lines = _parse_json3(raw)
        elif fname.endswith(".vtt"):
            try:
                with open(path, "r", encoding="utf-8") as fh:
                    raw = fh.read()
            except Exception:
                continue
            lines = _parse_vtt(raw)
        else:
            continue
        if not lines:
            continue
        m = re.search(r"\.([a-zA-Z]{2}(?:-[A-Za-z]+)?(?:-orig)?)\.(?:json3|vtt)$", fname)
        language = m.group(1) if m else "en"
        is_auto = "auto" in fname or "-orig" in fname
        parsed.append((is_auto, language, lines))
    if not parsed:
        return None
    # Real (False) sorts before auto (True), and within each group we prefer an
    # English track so the English-learning transcript is used whenever one
    # exists (covers Bilibili "ai-en" as well as standard "en"/"en-US").
    def sort_key(c):
        is_auto, language, _ = c
        return (is_auto, _lang_rank(language))

    parsed.sort(key=sort_key)
    is_auto, language, lines = parsed[0]
    return lines, language, is_auto


# ── yt-dlp invocation ────────────────────────────────────────────

# Bilibili tracking/query params that should not affect cache keys or yt-dlp extraction.
_BILI_NOISE_PARAMS = {
    "spm_id_from",
    "from_source",
    "from_spmid",
    "vd_source",
    "seid",
    "bvid",  # already in path; harmless but keeps URL tidy
}


def _normalize_bilibili_url(raw_url: str) -> str:
    """Strip Bilibili share/tracking params and trivial path variants so the same video shares a cache key."""
    parsed = urllib.parse.urlparse(raw_url)
    if parsed.netloc and "bilibili" not in parsed.netloc.lower():
        return raw_url
    # Force canonical scheme/host, keep www. for consistency with URLs the app
    # reconstructs, and remove a trailing slash from the path (e.g. /video/BVxx/
    # vs /video/BVxx normalize to the same key).
    netloc = parsed.netloc.lower()
    # Canonicalize any bilibili.com subdomain (m.bilibili.com, etc.) to www.
    if netloc.endswith(".bilibili.com") or netloc == "bilibili.com":
        netloc = "www.bilibili.com"
    path = parsed.path
    if path.endswith("/") and len(path) > 1:
        path = path[:-1]
    qs = urllib.parse.parse_qs(parsed.query)
    kept = {k: v for k, v in qs.items() if k not in _BILI_NOISE_PARAMS}
    new_qs = urllib.parse.urlencode(kept, doseq=True)
    parsed = parsed._replace(scheme="https", netloc=netloc, path=path, query=new_qs)
    return urllib.parse.urlunparse(parsed)


def _extract_part(raw_url: str):
    """Pull a Bilibili `?p=N` part selector out of a URL.

    Returns (clean_url, part) where clean_url has the selector stripped and
    part is an int (>1) or None. yt-dlp then selects the part via
    --playlist-items rather than the URL param, which is unambiguous.
    Tracking params are also stripped so share URLs with different UTM-like
    parameters hit the same cache entry.
    """
    raw_url = _normalize_bilibili_url(raw_url)
    parsed = urllib.parse.urlparse(raw_url)
    qs = urllib.parse.parse_qs(parsed.query)
    part = None
    if "p" in qs:
        try:
            part = int(qs["p"][0])
        except (ValueError, IndexError):
            part = None
        kept = {k: v for k, v in qs.items() if k != "p"}
        new_qs = urllib.parse.urlencode(kept, doseq=True)
        parsed = parsed._replace(query=new_qs)
        raw_url = urllib.parse.urlunparse(parsed)
    return raw_url, (part if part and part > 1 else None)


def _playlist_flag(part: Optional[int]) -> list:
    """yt-dlp flag selecting a specific playlist entry, or opting out."""
    if part and part > 1:
        return ["--playlist-items", str(part)]
    return ["--no-playlist"]


def _run_ytdlp(video_id_or_url: str, lang: str, *, is_url: bool = False, part: Optional[int] = None):
    target_url = video_id_or_url if is_url else f"https://www.youtube.com/watch?v={video_id_or_url}"
    with tempfile.TemporaryDirectory() as td:
        out_tmpl = os.path.join(td, "%(id)s")
        # Request a broad language set so we capture English (en / ai-en) and
        # Chinese (zh-CN / ai-zh) tracks. Bilibili tags its AI subtitles as
        # "ai-zh" / "ai-en", which a naive "zh.*" filter (used previously)
        # never matched — so those videos fell through to the slow Whisper ASR
        # even when a perfectly good subtitle track existed. _read_subtitle_file
        # then prefers an English track for the learning use case.
        sub_langs = "en,ai-en,zh-CN,ai-zh,en.*,zh.*,ai.*"  # ECHOLEARN_BILI_SUB_LANGS
        cmd = [
            sys.executable,
            "-m",
            "yt_dlp",
            "--skip-download",
            "--write-subs",
            "--write-auto-subs",
            "--sub-langs",
            sub_langs,
            "--sub-format",
            "vtt",
            "--quiet",
            "--no-warnings",
            *_playlist_flag(part),
            "--no-overwrites",
            "-o",
            out_tmpl,
            target_url,
        ]
        cmd += _site_args(target_url)
        try:
            subprocess.run(
                cmd,
                cwd=td,
                capture_output=True,
                text=True,
                timeout=YTDLP_TIMEOUT,
            )
        except subprocess.TimeoutExpired:
            return None
        result = _read_subtitle_file(td)
        if result:
            return result
    return None


def _fetch_meta(target_url: str, part: Optional[int] = None) -> dict:
    """Title / uploader / duration / thumbnail via `yt-dlp -J`, memoised."""
    cached = _cache_get(target_url, "__info__")
    if cached is not None:
        return cached

    cmd = [
        sys.executable,
        "-m",
        "yt_dlp",
        "--skip-download",
        "--dump-single-json",
        *_playlist_flag(part),
        "--quiet",
        "--no-warnings",
        target_url,
    ]
    cmd += _site_args(target_url)

    # The residential proxy is flaky for large Bilibili watch pages (tunnel
    # drops with IncompleteRead). A fresh process often lands on a stable IP.
    proc = None
    last_err = ""
    for attempt in range(1, YTDLP_RETRIES + 1):
        try:
            proc = subprocess.run(
                cmd, capture_output=True, text=True, timeout=YTDLP_TIMEOUT
            )
        except subprocess.TimeoutExpired:
            raise HTTPException(status_code=504, detail="Metadata lookup timed out")
        if proc.returncode == 0 and proc.stdout.strip():
            break
        last_err = proc.stderr.strip().splitlines()[-1] if proc.stderr else ""
        if attempt == YTDLP_RETRIES:
            detail = "Could not fetch video info"
            if last_err:
                detail += f" ({last_err})"
            raise HTTPException(status_code=404, detail=detail)

    if proc is None or proc.returncode != 0 or not proc.stdout.strip():
        raise HTTPException(status_code=404, detail="Could not fetch video info")

    try:
        meta = json.loads(proc.stdout)
    except json.JSONDecodeError:
        raise HTTPException(status_code=502, detail="Malformed metadata")

    payload = {
        "title": meta.get("title") or "",
        "ownerName": meta.get("uploader") or meta.get("channel") or "",
        "duration": meta.get("duration") or 0,
        "thumbnail": meta.get("thumbnail") or "",
    }
    _cache_put(target_url, "__info__", payload)
    return payload


# ── Whisper ASR via Groq ─────────────────────────────────────────

def _multipart(fields: dict, filename: str, blob: bytes, content_type: str):
    """Minimal multipart/form-data encoder.

    Hand-rolled so the service keeps its three-package dependency list and can
    be redeployed by copying a single file — no pip install on the VPS.
    """
    boundary = "----EchoLearn" + uuid.uuid4().hex
    body = bytearray()
    for key, value in fields.items():
        body += f"--{boundary}\r\n".encode()
        body += f'Content-Disposition: form-data; name="{key}"\r\n\r\n'.encode()
        body += f"{value}\r\n".encode()
    body += f"--{boundary}\r\n".encode()
    body += (
        f'Content-Disposition: form-data; name="file"; filename="{filename}"\r\n'
    ).encode()
    body += f"Content-Type: {content_type}\r\n\r\n".encode()
    body += blob
    body += b"\r\n"
    body += f"--{boundary}--\r\n".encode()
    return bytes(body), f"multipart/form-data; boundary={boundary}"


def _download_audio(target_url: str, td: str, part: Optional[int] = None) -> Optional[str]:
    """Grab the audio track and transcode to 16 kHz mono mp3 (Whisper's native
    sample rate — anything richer just inflates the upload)."""
    cmd = [
        sys.executable,
        "-m",
        "yt_dlp",
        "-f",
        "bestaudio/best",
        "--extract-audio",
        "--audio-format",
        "mp3",
        "--postprocessor-args",
        "ffmpeg:-ar 16000 -ac 1 -b:a 32k",
        *_playlist_flag(part),
        "--quiet",
        "--no-warnings",
        "--no-overwrites",
        "-o",
        os.path.join(td, "audio.%(ext)s"),
        target_url,
    ]
    cmd += _site_args(target_url)

    for attempt in range(1, YTDLP_RETRIES + 1):
        # Clear any partial download from a previous flaky attempt so the
        # --no-overwrites flag doesn't skip because of a broken fragment.
        for fname in os.listdir(td):
            try:
                os.remove(os.path.join(td, fname))
            except OSError:
                pass
        try:
            subprocess.run(
                cmd, cwd=td, capture_output=True, text=True, timeout=YTDLP_TIMEOUT
            )
        except subprocess.TimeoutExpired:
            return None
        for fname in sorted(os.listdir(td)):
            if fname.endswith(".mp3"):
                return os.path.join(td, fname)
    return None


def _audio_cache_path(target_url: str, part: Optional[int]) -> str:
    """Stable cache filename for a (url, part) pair.

    Bilibili share URLs often carry tracking params (spm_id_from, vd_source,
    etc.) that would otherwise fragment the cache. Normalize before hashing.
    """
    normalized = _normalize_bilibili_url(target_url)
    key = f"{normalized}|p={part}"
    digest = hashlib.md5(key.encode("utf-8")).hexdigest()
    return os.path.join(AUDIO_CACHE_DIR, f"{digest}.mp3")


def _extract_playback_audio(target_url: str, part: Optional[int] = None) -> Optional[str]:
    """Download the audio track at a *listenable* bitrate and cache it on disk.

    Unlike _download_audio (which targets Whisper at 16 kHz/32 kbps), this keeps
    full sample rate and 128 kbps so the in-app audio-only player sounds normal.
    Returns the cached .mp3 path, or None on failure.
    """
    out_path = _audio_cache_path(target_url, part)
    if os.path.exists(out_path) and os.path.getsize(out_path) > 0:
        return out_path

    cmd = [
        sys.executable,
        "-m",
        "yt_dlp",
        "-f",
        "bestaudio/best",
        "--extract-audio",
        "--audio-format",
        "mp3",
        "--postprocessor-args",
        "ffmpeg:-ar 44100 -ac 2 -b:a 128k",
        *_playlist_flag(part),
        "--quiet",
        "--no-warnings",
        "-o",
        out_path,
        target_url,
    ]
    cmd += _site_args(target_url)

    for attempt in range(1, YTDLP_RETRIES + 1):
        # Clear any partial file so a fresh attempt isn't skipped.
        try:
            if os.path.exists(out_path):
                os.remove(out_path)
        except OSError:
            pass
        try:
            subprocess.run(
                cmd, cwd=AUDIO_CACHE_DIR, capture_output=True, text=True, timeout=YTDLP_TIMEOUT
            )
        except subprocess.TimeoutExpired:
            return None
        if os.path.exists(out_path) and os.path.getsize(out_path) > 0:
            return out_path
    return None


def _groq_transcribe(path: str) -> dict:
    """Send one audio file to Groq Whisper and return the EchoLearn payload.

    The language is deliberately auto-detected rather than hinted: the point of
    ASR on Bilibili is the English-language content hosted there, and pinning
    the hint to zh would wreck exactly those videos.
    """
    with open(path, "rb") as fh:
        blob = fh.read()

    if len(blob) > GROQ_MAX_BYTES:
        raise HTTPException(
            status_code=413,
            detail=f"Audio is {len(blob) // 1024 // 1024} MB, over the 25 MB Groq limit",
        )

    body, content_type = _multipart(
        {"model": GROQ_MODEL, "response_format": "verbose_json"},
        "audio.mp3",
        blob,
        "audio/mpeg",
    )
    req = urllib.request.Request(
        GROQ_ENDPOINT,
        data=body,
        headers={
            "Authorization": f"Bearer {GROQ_API_KEY}",
            "Content-Type": content_type,
            # Groq sits behind Cloudflare, which bans the default
            # "Python-urllib/3.x" UA with HTTP 403 / error 1010. Send a
            # non-default UA so the request is accepted.
            "User-Agent": "EchoLearn-VPS/1.0 (groq-asr)",
        },
        method="POST",
    )

    # Groq works directly from this VPS (verified end-to-end with no proxy),
    # and routing it through the residential proxy only adds a flaky hop
    # (Broken pipe / IncompleteRead). Call it directly and retry a couple of
    # times to absorb Groq's occasional transient 403/abuse throttle on the
    # free tier.
    raw = None
    last_err = ""
    for attempt in range(1, 3):
        try:
            with urllib.request.urlopen(req, timeout=GROQ_TIMEOUT) as resp:
                raw = json.load(resp)
            break
        except urllib.error.HTTPError as exc:
            last_err = exc.read().decode("utf-8", "ignore")[:400]
            # Surface 429 (out of quota) as-is; other HTTP errors may be
            # transient, so retry once.
            if exc.code == 429:
                raise HTTPException(status_code=429, detail=f"Groq HTTP 429: {last_err}")
            if attempt < 2:
                time.sleep(1)
                continue
            status = 502
            raise HTTPException(status_code=status, detail=f"Groq HTTP {exc.code}: {last_err}")
        except Exception as exc:  # noqa: BLE001 - transient network blips
            last_err = str(exc)
            if attempt < 2:
                time.sleep(1)
                continue
            raise HTTPException(status_code=502, detail=f"Groq request failed: {exc}")

    segments = raw.get("segments") or []
    lines = [
        {
            "id": f"yt_{i + 1}",
            "start": round(float(seg.get("start") or 0), 3),
            "end": round(float(seg.get("end") or 0), 3),
            "text": (seg.get("text") or "").strip(),
        }
        for i, seg in enumerate(segments)
        if (seg.get("text") or "").strip()
    ]

    if not lines:
        text = (raw.get("text") or "").strip()
        if not text:
            raise HTTPException(status_code=404, detail="Whisper returned no speech")
        lines = [{"id": "yt_1", "start": 0, "end": 0, "text": text}]

    return {
        "lines": lines,
        "language": raw.get("language") or "unknown",
        "isAutoGenerated": True,
        "source": "asr",
    }


