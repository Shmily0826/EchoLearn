def _is_english(language: Optional[str]) -> bool:
    """Whether a subtitle language code denotes English (incl. Bilibili 'ai-en')."""
    l = (language or "").lower()
    return l in ("en", "ai-en") or l.startswith("en")


def _lang_rank(language: Optional[str]) -> int:
    """Sort rank for subtitle language: English first, then Chinese, then rest."""
    l = (language or "").lower()
    if l in ("en", "ai-en") or l.startswith("en"):
        return 0
    if l.startswith("zh") or l == "ai-zh":
        return 1
    return 2


def _extract_bvid(target_url: str):
    """Pull the BV id out of a Bilibili URL (or return None).

    Bilibili BV ids are case-sensitive after the ``BV`` prefix. Match the
    prefix case-insensitively, but preserve every character in the payload;
    uppercasing the whole id turns e.g. ``BV1emBiYcEAV`` into a different id.
    """
    m = re.search(r"(BV[0-9A-Za-z]+)", target_url, re.IGNORECASE)
    return ("BV" + m.group(1)[2:]) if m else None


def _clean_bvid(raw_id: str | None):
    """Strip yt-dlp's playlist `_pN` suffix from a Bilibili id.

    When a b23.tv short link points at a specific part of a multi-part video,
    yt-dlp reports the id as e.g. `BV1xx_p1`. The player iframe and the Bilibili
    view API need the base id (`BV1xx`), so strip the suffix and report the part
    separately. Returns (base_bvid, part_or_None).
    """
    if not raw_id:
        return None, None
    m = re.match(r"^(BV[0-9A-Za-z]+)_p(\d+)$", raw_id)
    if m:
        return m.group(1), int(m.group(2))
    return raw_id, None


def _bilibili_parts(bvid: str):
    """Return the part list for a Bilibili video via its public view API.

    The view API (api.bilibili.com/x/web-interface/view) answers the VPS
    datacenter IP fine — only the *watch page* returns HTTP 412 — so no
    proxy is needed. Returns {"partCount": N, "parts": [{"index", "title"}]}
    or None on any failure (the caller then simply skips the part picker).
    """
    api = f"https://api.bilibili.com/x/web-interface/view?bvid={bvid}"
    req = urllib.request.Request(
        api,
        headers={
            "User-Agent": (
                "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
                "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
            ),
            "Referer": "https://www.bilibili.com/",
        },
    )
    try:
        with _urlopen_no_proxy(req, timeout=10) as resp:
            data = json.loads(resp.read().decode("utf-8", "ignore"))
    except Exception:
        return None
    if data.get("code") != 0:
        return None
    pages = (data.get("data") or {}).get("pages") or []
    parts = [{"index": p.get("page"), "title": p.get("part") or ""} for p in pages]
    return {"partCount": len(parts), "parts": parts}


# ── Bilibili API-direct extraction (no proxy, no yt-dlp watch-page 412) ──
#
# Bilibili's JSON APIs (view + playurl) answer the VPS datacenter IP fine,
# and the media CDN (bilivideo.com) serves anonymous clients directly. The
# only thing that 412s from a datacenter IP is the *watch page* HTML, which
# yt-dlp's extractor hits — so we bypass yt-dlp entirely for Bilibili and
# pull the audio straight from the DASH manifest. This also means the
# residential proxy (which Bilibili blocks wholesale anyway) is never used
# for Bilibili, saving both latency and Proxy-Cheap bandwidth.

_BILI_UA = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
)
_BILI_REFERER = "https://www.bilibili.com/"


def _resolve_bilibili_url(url: str) -> str:
    """Follow b23.tv short links to the canonical bilibili.com URL."""
    if "b23.tv" not in url:
        return url
    headers = {"User-Agent": _BILI_UA, "Referer": _BILI_REFERER}
    req = urllib.request.Request(url, headers=headers)
    try:
        with _urlopen_no_proxy(req, timeout=10) as resp:
            return resp.geturl()
    except Exception:
        # b23.tv is a webpage redirect and can return 412 to datacenter IPs,
        # even though api.bilibili.com and the media CDN remain public. Use
        # the configured residential proxy only for this redirect step; all
        # subsequent view/playurl/API and CDN requests stay direct.
        if not YTDLP_PROXY:
            return url
        try:
            proxy = urllib.request.ProxyHandler({"http": YTDLP_PROXY, "https": YTDLP_PROXY})
            class _NoRedirect(urllib.request.HTTPRedirectHandler):
                def redirect_request(self, req, fp, code, msg, headers, new):
                    return None
            opener = urllib.request.build_opener(proxy, _NoRedirect())
            try:
                with opener.open(req, timeout=20) as resp:
                    location = resp.headers.get("Location")
            except urllib.error.HTTPError as exc:
                location = exc.headers.get("Location")
            if location:
                return urllib.parse.urljoin(url, location)
        except Exception:
            pass
        # Some HTTPS proxies fail when urllib follows the redirect, but still
        # return the Location header. Ask curl for headers only as a final
        # redirect-resolution fallback and never follow the destination page.
        try:
            proc = subprocess.run(
                ["curl", "-sS", "-I", "--max-redirs", "0", "--proxy", YTDLP_PROXY,
                 "-A", _BILI_UA, url],
                capture_output=True, text=True, timeout=20,
            )
            for line in proc.stdout.splitlines():
                if line.lower().startswith("location:"):
                    return urllib.parse.urljoin(url, line.split(":", 1)[1].strip())
        except Exception:
            pass
        return url


def _bilibili_view(bvid: str):
    """Full view-API payload: title, owner, duration, and per-part cids."""
    cached = _BILI_VIEW_CACHE.get(bvid)
    if cached and cached[0] > time.time():
        return cached[1]
    api = f"https://api.bilibili.com/x/web-interface/view?bvid={bvid}"
    headers = {
        "User-Agent": _BILI_UA,
        "Referer": _BILI_REFERER,
        "Origin": "https://www.bilibili.com",
        "Accept": "application/json, text/plain, */*",
    }
    # The API is normally reliable from the VPS, but occasional upstream
    # connection resets/empty responses were causing the whole ASR request to
    # fail before audio extraction. Retry the cheap metadata call briefly.
    for attempt in range(3):
        req = urllib.request.Request(api, headers=headers)
        try:
            with _urlopen_no_proxy(req, timeout=15) as resp:
                data = json.loads(resp.read().decode("utf-8", "ignore"))
            if data.get("code") == 0:
                d = data.get("data") or {}
                pages = [
                    {"index": p.get("page"), "cid": p.get("cid"),
                     "title": p.get("part") or "", "duration": p.get("duration") or 0}
                    for p in (d.get("pages") or [])
                ]
                result = {
                    "title": d.get("title") or "",
                    "owner": (d.get("owner") or {}).get("name") or "",
                    "duration": d.get("duration") or 0,
                    "pages": pages,
                }
                _BILI_VIEW_CACHE[bvid] = (time.time() + _BILI_VIEW_CACHE_TTL, result)
                return result
        except Exception:
            pass
        if attempt < 2:
            time.sleep(0.75 * (attempt + 1))
    return None


def _bilibili_play_parse(data):
    """Extract a usable audio baseUrl from a playurl API response, or None."""
    if not isinstance(data, dict) or data.get("code") != 0:
        return None
    payload = data.get("data")
    # Legacy shape: data is a list of durl entries (muxed FLV/MP4 with audio).
    # The playurl API returns this intermittently (e.g. on some CDN nodes).
    if isinstance(payload, list):
        if not payload:
            return None
        return payload[0].get("url") or payload[0] if isinstance(payload[0], str) else payload[0].get("baseUrl")
    dash = (payload or {}).get("dash") or {}
    audios = dash.get("audio") or []
    if audios:
        audios.sort(key=lambda a: a.get("bandwidth") or 0, reverse=True)
        return audios[0].get("baseUrl")
    # Fallback: some playurl responses omit the DASH audio track but still
    # return a muxed stream via `durl`. That carries audio, fine for ASR.
    durl = (payload or {}).get("durl") or []
    if durl:
        return durl[0].get("url") or durl[0].get("baseUrl")
    return None


def _bilibili_playurl(bvid: str, cid: int):
    """Best audio baseUrl for a (bvid, cid), or None.

    Retries once because the playurl API occasionally returns a malformed /
    audio-less payload on the first hit (CDN-node dependent).
    """
    api = (
        f"https://api.bilibili.com/x/player/playurl?bvid={bvid}"
        f"&cid={cid}&qn=64&fnval=16&fourk=1"
    )
    req = urllib.request.Request(
        api, headers={"User-Agent": _BILI_UA, "Referer": _BILI_REFERER}
    )
    last = None
    for _ in range(2):
        try:
            with _urlopen_no_proxy(req, timeout=10) as resp:
                last = json.loads(resp.read().decode("utf-8", "ignore"))
        except Exception:
            last = None
        url = _bilibili_play_parse(last)
        if url:
            return url
    return None


def _bilibili_cid_for_part(view, part: Optional[int]):
    """Return the cid for the requested part (1-indexed), defaulting to part 1."""
    pages = (view or {}).get("pages") or []
    if not pages:
        return None
    if part and part > 1:
        for p in pages:
            if p.get("index") == part:
                return p.get("cid")
    return pages[0].get("cid")


def _download_bilibili_audio(base_url: str, out_path: str, ar: int = 16000, ab: int = 32) -> bool:
    """Download a Bilibili DASH audio URL (CDN, no proxy) and transcode to mp3.

    `ar`/`ab` select the Whisper-friendly 16 kHz/32 kbps profile for ASR, or a
    listenable 44.1 kHz/64 kbps profile for the audio player.
    """
    raw = out_path + ".raw"
    req = urllib.request.Request(
        base_url, headers={"User-Agent": _BILI_UA, "Referer": _BILI_REFERER}
    )
    try:
        with _urlopen_no_proxy(req, timeout=90) as resp, open(raw, "wb") as fh:
            while True:
                chunk = resp.read(1 << 16)
                if not chunk:
                    break
                fh.write(chunk)
    except Exception:
        try:
            os.remove(raw)
        except OSError:
            pass
        return False
    try:
        subprocess.run(
            ["ffmpeg", "-y", "-i", raw, "-ar", str(ar), "-ac", "1",
             "-b:a", f"{ab}k", out_path],
            capture_output=True, text=True, timeout=120,
        )
    except Exception:
        pass
    finally:
        try:
            os.remove(raw)
        except OSError:
            pass
    return os.path.exists(out_path) and os.path.getsize(out_path) > 0


def _bilibili_asr(url: str, part: Optional[int] = None) -> dict:
    """Full ASR pipeline for a Bilibili video via the public APIs (no proxy)."""
    resolved = _resolve_bilibili_url(url)
    bvid = _extract_bvid(resolved)
    if not bvid:
        raise HTTPException(status_code=400, detail="Could not parse Bilibili id")
    view = _bilibili_view(bvid)
    if not view:
        raise HTTPException(status_code=404, detail="Bilibili view API failed")
    cid = _bilibili_cid_for_part(view, part)
    if not cid:
        raise HTTPException(status_code=404, detail="Bilibili part not found")
    base_url = _bilibili_playurl(bvid, cid)
    if not base_url:
        raise HTTPException(status_code=404, detail="Bilibili playurl API failed")
    with tempfile.TemporaryDirectory() as td:
        mp3 = os.path.join(td, "audio.mp3")
        if not _download_bilibili_audio(base_url, mp3, ar=16000, ab=32):
            raise HTTPException(status_code=502, detail="Could not download Bilibili audio")
        return _groq_transcribe(mp3)


def _bilibili_audio(url: str, part: Optional[int], out_path: str) -> bool:
    """Fetch + transcode a listenable Bilibili audio track into out_path."""
    resolved = _resolve_bilibili_url(url)
    bvid = _extract_bvid(resolved)
    if not bvid:
        return False
    view = _bilibili_view(bvid)
    if not view:
        return False
    cid = _bilibili_cid_for_part(view, part)
    if not cid:
        return False
    base_url = _bilibili_playurl(bvid, cid)
    if not base_url:
        return False
    return _download_bilibili_audio(base_url, out_path, ar=44100, ab=64)


def _host_allowed(target_url: str) -> bool:
    """Only let known hosts through so the endpoint can't be used as an
    open yt-dlp relay for arbitrary sites."""
    if not target_url.startswith(("http://", "https://")):
        return False
    return any(h in target_url for h in _ALLOWED_HOSTS)


def _site_args(target_url: str) -> list:
    """Per-site yt-dlp flags.

    - The residential proxy is applied via *environment variables* (see
      `_proxy_env`), NOT the `--proxy` CLI flag. Doing it in the env lets us set
      NO_PROXY so Bilibili's media CDN (bilivideo.com / akamaized.net) is reached
      directly from the datacenter IP while the watch page still rides the proxy
      (it returns 412 otherwise). Downloading the multi-MB audio straight from
      the CDN is ~17x faster and far less prone to the proxy dropping mid-transfer
      — this is "Plan C".
    - Cookies (YTDLP_COOKIES, e.g. a Bilibili SESSDATA jar) are applied whenever
      the file exists. Bilibili only exposes subtitle tracks to logged-in
      sessions, so the cookie is what unlocks real subtitles there — without it
      the transcript route falls through to ASR.
    """
    args: list = []
    if YTDLP_COOKIES and os.path.exists(YTDLP_COOKIES):
        args += ["--cookies", YTDLP_COOKIES]
    return args


def _cookie_args(target_url: str) -> list:
    """Like _site_args but cookies only — no proxy.

    Used as a fallback when the residential proxy tunnel is down: with a valid
    YouTube account cookie in YTDLP_COOKIES plus the --remote-components n-solver,
    yt-dlp can fetch captions directly from the datacenter IP without the proxy.
    """
    args: list = []
    if YTDLP_COOKIES and os.path.exists(YTDLP_COOKIES):
        args += ["--cookies", YTDLP_COOKIES]
    return args


# Bilibili media CDNs that serve fine from the datacenter IP without the
# residential proxy. Routing these direct (instead of through the flaky proxy)
# is the core of Plan C: the watch page still needs the proxy (412 otherwise)
# but the multi-MB audio/video download no longer rides the proxy that tends to
# drop large transfers.
_BILI_MEDIA_NO_PROXY = "bilivideo.com,akamaized.net,mcdn.bilivideo.cn"


def _proxy_env(target_url: str) -> dict:
    """Build a subprocess env that routes yt-dlp through the residential proxy
    for YouTube and Bilibili, but sends Bilibili's media CDN traffic direct.

    We set the proxy via environment variables (not the ``--proxy`` CLI flag) so
    that NO_PROXY can carve out the Bilibili media hosts. yt-dlp honours NO_PROXY
    for its urllib-based downloads, so the large audio transfer goes straight to
    the CDN — ~17x faster and far more reliable than the proxy.
    """
    env = dict(os.environ)
    if YTDLP_PROXY and (_is_youtube(target_url) or _is_bilibili(target_url)):
        for k in ("HTTP_PROXY", "HTTPS_PROXY", "ALL_PROXY",
                  "http_proxy", "https_proxy", "all_proxy"):
            env[k] = YTDLP_PROXY
        if _is_bilibili(target_url):
            # Watch page + playurl API still use the proxy; only the media CDN
            # (bilivideo.com / akamaized.net) is reached directly.
            for k in ("NO_PROXY", "no_proxy"):
                env[k] = _BILI_MEDIA_NO_PROXY
        else:
            # YouTube: keep everything on the proxy (it's what unblocks it).
            env.pop("NO_PROXY", None)
            env.pop("no_proxy", None)
    else:
        # No proxy wanted — make sure none leaks from the parent env.
        for k in ("HTTP_PROXY", "HTTPS_PROXY", "ALL_PROXY",
                  "http_proxy", "https_proxy", "all_proxy",
                  "NO_PROXY", "no_proxy"):
            env.pop(k, None)
    return env


def _no_proxy_env() -> dict:
    """Subprocess env with the proxy fully removed — used by the YouTube cookie
    fallback that fetches captions straight from the datacenter IP."""
    env = dict(os.environ)
    for k in ("HTTP_PROXY", "HTTPS_PROXY", "ALL_PROXY",
              "http_proxy", "https_proxy", "all_proxy",
              "NO_PROXY", "no_proxy"):
        env.pop(k, None)
    return env


def _has_youtube_cookies() -> bool:
    """True if the cookie jar contains a YouTube session (so the no-proxy
    fallback is worth attempting)."""
    if not (YTDLP_COOKIES and os.path.exists(YTDLP_COOKIES)):
        return False
    try:
        with open(YTDLP_COOKIES, encoding="utf-8") as fh:
            return any(".youtube.com" in line for line in fh)
    except OSError:
        return False

# ── In-memory TTL cache (keyed by video_id:lang) ──────────────
# Protects the single VPS IP from repeat YouTube hits on popular videos and
# speeds up repeated fetches of the same video+lang. Only successful results
# are cached; failures are always retried.
_CACHE: "OrderedDict[str, tuple[float, dict]]" = OrderedDict()
_CACHE_MAX = 2000


def _cache_get(video_id: str, lang: str):
    key = f"{video_id}:{lang}"
    item = _CACHE.get(key)
    if item is None:
        return None
    expiry, payload = item
    if expiry < time.time():
        _CACHE.pop(key, None)
        return None
    _CACHE.move_to_end(key)  # LRU touch
    return payload


def _cache_put(video_id: str, lang: str, payload: dict):
    key = f"{video_id}:{lang}"
    _CACHE[key] = (time.time() + YTDLP_CACHE_TTL, payload)
    _CACHE.move_to_end(key)
    if len(_CACHE) > _CACHE_MAX:
        _CACHE.popitem(last=False)  # evict oldest


# ── Parsers ───────────────────────────────────────────────────────

def _parse_json3(raw: dict) -> list:
    events = raw.get("events", []) if isinstance(raw, dict) else []
    lines = []
    idx = 0
    for ev in events:
        segs = ev.get("segs") or []
        text = "".join(s.get("utf8", "") for s in segs).strip()
        if not text:
            continue
        start = (ev.get("tStartMs") or 0) / 1000.0
        dur = ev.get("dDurationMs") or 0
        lines.append(
            {
                "id": f"yt_{idx + 1}",
                "start": round(start, 3),
                "end": round(start + dur / 1000.0, 3),
                "text": text,
            }
        )
        idx += 1
    return lines


def _parse_vtt(text: str) -> list:
    # Parse every cue (timestamp line + text) into a raw record. We keep the
    # RAW text so we can later detect YouTube's auto-caption (ASR) overlap format.
    cues = []
    idx = 0
    cue_re = re.compile(
        r"(\d{1,2}:)?\d{1,2}:\d{2}\.\d{1,3}\s*-->\s*(\d{1,2}:)?\d{1,2}:\d{2}\.\d{1,3}"
    )
    ts_matches = list(cue_re.finditer(text))
    for i, m in enumerate(ts_matches):
        start = _vtt_time_to_sec(m.group(0).split("-->")[0].strip())
        end = _vtt_time_to_sec(m.group(0).split("-->")[1].strip())
        # The cue body runs from the end of this timestamp *line* to the start of
        # the next one. Grouping this way is robust to the blank line YouTube
        # sometimes inserts between a timestamp and its text (which a naive
        # blank-line split would otherwise orphan into a timestamp-less block).
        # We skip to after the newline so trailing timestamp params such as
        # "align:start position:0%" are not treated as caption text.
        nl = text.find("\n", m.end())
        body_start = nl + 1 if nl != -1 else len(text)
        body_end = ts_matches[i + 1].start() if i + 1 < len(ts_matches) else len(text)
        raw = text[body_start:body_end]
        # ASR cues carry per-word timing tags like <00:00:00.880> or <c>word</c>.
        had_inline = bool(re.search(r"<\d\d:\d\d|<\s*c[ >]", raw))
        cues.append(
            {"start": round(start, 3), "end": round(end, 3), "raw": raw, "had_inline": had_inline}
        )

    if not cues:
        return []

    # YouTube auto-captions (ASR) emit a "growing window" of text per word-timed
    # cue (each window is a super-set of the previous one) followed by a ~0.01s
    # "echo" cue that repeats the just-finalised line. Keeping every cue therefore
    # produces heavily overlapping / duplicated transcript lines. Collapse them into
    # clean, non-overlapping lines by retaining only the *new* text introduced at
    # each window transition. Manually-written captions have no inline tags, so they
    # fall through to the simple one-cue-per-line path below.
    # ASR_COLLAPSE_V1
    asr = any(c["had_inline"] for c in cues)
    if not asr:
        out = []
        for c in cues:
            t = re.sub(r"<[^>]+>", "", c["raw"]).strip()
            if not t:
                continue
            out.append({"id": f"yt_{idx + 1}", "start": c["start"], "end": c["end"], "text": t})
            idx += 1
        return out

    cues.sort(key=lambda c: c["start"])
    out = []
    consumed = ""
    for c in cues:
        t = re.sub(r"<[^>]+>", "", c["raw"]).strip()
        if not t:
            continue
        if t.startswith(consumed):
            new = t[len(consumed):].strip()
        else:
            # Strip the longest prefix of t that matches a suffix of what we have
            # already absorbed (handles sentence resets / overlapping windows).
            new = t
            for k in range(min(len(t), len(consumed)), 0, -1):
                if consumed.endswith(t[:k]):
                    new = t[k:].strip()
                    break
        if new:
            out.append({"id": f"yt_{idx + 1}", "start": c["start"], "end": c["end"], "text": new})
            idx += 1
            consumed = t
    return out


def _vtt_time_to_sec(s: str) -> float:
    s = s.strip()
    # Formats: HH:MM:SS.mmm or MM:SS.mmm
    parts = s.split(":")
    parts = [float(p) for p in parts]
    if len(parts) == 3:
        h, m, sec = parts
    else:
        h, m, sec = 0, parts[0], parts[1]
    return h * 3600 + m * 60 + sec


def _read_subtitle_file(td: str):
    """Return (lines, language, is_auto) for the best usable subtitle file.

    Hand-written subtitles are preferred over auto-generated ones; this matters
    most for Bilibili, where real tracks (when present) are far cleaner than the
    auto captions.
    """
    parsed = []
    # The subtitle filename is yt-dlp's %(id)s template, which for Bilibili is the
    # BV id. Capture it so the app can wire up the player/title for videos reached
    # via a b23.tv short link (where the client only has the short code).
    bvid = None
    for fname in sorted(os.listdir(td)):
        path = os.path.join(td, fname)
        if fname.endswith(".json3"):
            try:
                with open(path, "r", encoding="utf-8") as fh:
                    raw = json.load(fh)
            except Exception:
                continue
            lines = _parse_json3(raw)
        elif fname.endswith(".vtt"):
            try:
                with open(path, "r", encoding="utf-8") as fh:
                    raw = fh.read()
            except Exception:
                continue
            lines = _parse_vtt(raw)
        else:
            continue
        if not lines:
            continue
        if bvid is None:
            m_id = re.match(r"^(BV[0-9A-Za-z]+)\.", fname)
            if m_id:
                bvid, _ = _clean_bvid(m_id.group(1))
        m = re.search(r"\.([a-zA-Z]{2}(?:-[A-Za-z]+)?(?:-orig)?)\.(?:json3|vtt)$", fname)
        language = m.group(1) if m else "en"
        is_auto = "auto" in fname or "-orig" in fname
        parsed.append((is_auto, language, lines))
    if not parsed:
        return None
    # Real (False) sorts before auto (True), and within each group we prefer an
    # English track so the English-learning transcript is used whenever one
    # exists (covers Bilibili "ai-en" as well as standard "en"/"en-US").
    def sort_key(c):
        is_auto, language, _ = c
        return (is_auto, _lang_rank(language))

    parsed.sort(key=sort_key)
    is_auto, language, lines = parsed[0]
    return lines, language, is_auto, bvid


# ── yt-dlp invocation ────────────────────────────────────────────

# Bilibili tracking/query params that should not affect cache keys or yt-dlp extraction.
_BILI_NOISE_PARAMS = {
    "spm_id_from",
    "from_source",
    "from_spmid",
    "vd_source",
    "seid",
    "bvid",  # already in path; harmless but keeps URL tidy
}


def _normalize_bilibili_url(raw_url: str) -> str:
    """Strip Bilibili share/tracking params and trivial path variants so the same video shares a cache key."""
    parsed = urllib.parse.urlparse(raw_url)
    if parsed.netloc and "bilibili" not in parsed.netloc.lower():
        return raw_url
    # Force canonical scheme/host, keep www. for consistency with URLs the app
    # reconstructs, and remove a trailing slash from the path (e.g. /video/BVxx/
    # vs /video/BVxx normalize to the same key).
    netloc = parsed.netloc.lower()
    # Canonicalize any bilibili.com subdomain (m.bilibili.com, etc.) to www.
    if netloc.endswith(".bilibili.com") or netloc == "bilibili.com":
        netloc = "www.bilibili.com"
    path = parsed.path
    if path.endswith("/") and len(path) > 1:
        path = path[:-1]
    qs = urllib.parse.parse_qs(parsed.query)
    kept = {k: v for k, v in qs.items() if k not in _BILI_NOISE_PARAMS}
    new_qs = urllib.parse.urlencode(kept, doseq=True)
    parsed = parsed._replace(scheme="https", netloc=netloc, path=path, query=new_qs)
    return urllib.parse.urlunparse(parsed)


def _extract_part(raw_url: str):
    """Pull a Bilibili `?p=N` part selector out of a URL.

    Returns (clean_url, part) where clean_url has the selector stripped and
    part is an int (>1) or None. yt-dlp then selects the part via
    --playlist-items rather than the URL param, which is unambiguous.
    Tracking params are also stripped so share URLs with different UTM-like
    parameters hit the same cache entry.
    """
    raw_url = _normalize_bilibili_url(raw_url)
    parsed = urllib.parse.urlparse(raw_url)
    qs = urllib.parse.parse_qs(parsed.query)
    part = None
    if "p" in qs:
        try:
            part = int(qs["p"][0])
        except (ValueError, IndexError):
            part = None
        kept = {k: v for k, v in qs.items() if k != "p"}
        new_qs = urllib.parse.urlencode(kept, doseq=True)
        parsed = parsed._replace(query=new_qs)
        raw_url = urllib.parse.urlunparse(parsed)
    return raw_url, (part if part and part > 1 else None)


def _playlist_flag(part: Optional[int]) -> list:
    """yt-dlp flag selecting a specific playlist entry, or opting out."""
    if part and part > 1:
        return ["--playlist-items", str(part)]
    return ["--no-playlist"]


def _run_ytdlp(video_id_or_url: str, lang: str, *, is_url: bool = False, part: Optional[int] = None):
    target_url = video_id_or_url if is_url else f"https://www.youtube.com/watch?v={video_id_or_url}"
    sub_langs = "en,ai-en,zh-CN,ai-zh,en.*,zh.*,ai.*"  # ECHOLEARN_BILI_SUB_LANGS
    base_cmd = [
        sys.executable,
        "-m",
        "yt_dlp",
        "--js-runtimes",
        "node",
        "--remote-components",
        "ejs:github",
        "--skip-download",
        "--write-subs",
        "--write-auto-subs",
        "--sub-langs",
        sub_langs,
        "--sub-format",
        "vtt",
        "--quiet",
        "--no-warnings",
        *_playlist_flag(part),
        "--no-overwrites",
        target_url,
    ]
    # Bilibili: yt-dlp's watch-page extractor 412s from datacenter IPs AND from
    # the proxy pool, so the proxy is useless there — run without it. (The
    # /api/asr and /api/audio routes bypass yt-dlp for Bilibili entirely via the
    # public APIs; this path only matters if a real subtitle track exists.)
    # YouTube: the TVHTML5 client bypasses the datacenter bot-check, so try NO
    # proxy first (fast, free) and only fall back to the proxy if that fails.
    if _is_bilibili(target_url):
        cmds = [(base_cmd + _site_args(target_url), _no_proxy_env())]
    else:
        cmds = [(base_cmd + _site_args(target_url), _no_proxy_env())]
        if YTDLP_PROXY:
            cmds.append((base_cmd + _site_args(target_url), _proxy_env(target_url)))
    for cmd, env in cmds:
        with tempfile.TemporaryDirectory() as td:
            full = cmd + ["-o", os.path.join(td, "%(id)s")]
            try:
                subprocess.run(
                    full,
                    cwd=td,
                    capture_output=True,
                    text=True,
                    timeout=YTDLP_TIMEOUT,
                    env=env,
                )
            except subprocess.TimeoutExpired:
                continue
            result = _read_subtitle_file(td)
            if result:
                return result
    return None


def _fetch_meta(target_url: str, part: Optional[int] = None, *, attempts: int = None, timeout: int = None) -> dict:
    """Title / uploader / duration / thumbnail via `yt-dlp -J`, memoised.

    `attempts` / `timeout` override the global YTDLP_RETRIES / YTDLP_TIMEOUT so
    callers with a tight deadline (e.g. the audio player, which must beat the
    Worker's 180s window) can fail the metadata lookup faster instead of
    burning the whole budget on a flaky proxy.
    """
    cached = _cache_get(target_url, "__info__")
    if cached is not None:
        return cached

    # Bilibili: skip yt-dlp (watch-page 412) and use the view API directly.
    if _is_bilibili(target_url):
        resolved = _resolve_bilibili_url(target_url)
        bvid = _extract_bvid(resolved)
        view = _bilibili_view(bvid) if bvid else None
        if not view:
            raise HTTPException(status_code=404, detail="Could not fetch Bilibili info")
        # A multi-part video reports the TOTAL duration in view["duration"]; for
        # the ASR/audio limit check and the player we want the selected part's
        # duration, which lives on the per-page record. Default to part 1 when no
        # explicit ?p= selector is present.
        sel = part if part else 1
        part_dur = None
        for p in view.get("pages") or []:
            if p.get("index") == sel and p.get("duration"):
                part_dur = p["duration"]
                break
        if not part_dur:
            part_dur = view["duration"]
        payload = {
            "title": view["title"],
            "ownerName": view["owner"],
            "duration": part_dur,
            "thumbnail": "",
            "bvid": bvid,
        }
        parts = _bilibili_parts(bvid) if bvid else None
        if parts:
            payload["partCount"] = parts["partCount"]
            payload["parts"] = parts["parts"]
        _cache_put(target_url, "__info__", payload)
        return payload

    attempts = attempts or YTDLP_RETRIES
    timeout = timeout or YTDLP_TIMEOUT

    cmd = [
        sys.executable,
        "-m",
        "yt_dlp",
        "--js-runtimes",
        "node",
        "--remote-components",
        "ejs:github",
        "--skip-download",
        "--dump-single-json",
        *_playlist_flag(part),
        "--quiet",
        "--no-warnings",
        target_url,
    ]
    cmd += _site_args(target_url)

    # The residential proxy is flaky for large Bilibili watch pages (tunnel
    # drops with IncompleteRead). A fresh process often lands on a stable IP.
    proc = None
    last_err = ""
    for attempt in range(1, attempts + 1):
        try:
            proc = subprocess.run(
                cmd, capture_output=True, text=True, timeout=timeout,
                env=_proxy_env(target_url),
            )
        except subprocess.TimeoutExpired:
            raise HTTPException(status_code=504, detail="Metadata lookup timed out")
        if proc.returncode == 0 and proc.stdout.strip():
            break
        last_err = proc.stderr.strip().splitlines()[-1] if proc.stderr else ""
        if attempt == attempts:
            detail = "Could not fetch video info"
            if last_err:
                detail += f" ({last_err})"
            raise HTTPException(status_code=404, detail=detail)

    if proc is None or proc.returncode != 0 or not proc.stdout.strip():
        raise HTTPException(status_code=404, detail="Could not fetch video info")

    try:
        meta = json.loads(proc.stdout)
    except json.JSONDecodeError:
        raise HTTPException(status_code=502, detail="Malformed metadata")

    payload = {
        "title": meta.get("title") or "",
        "ownerName": meta.get("uploader") or meta.get("channel") or "",
        "duration": meta.get("duration") or 0,
        "thumbnail": meta.get("thumbnail") or "",
        "bvid": _clean_bvid(meta.get("id"))[0] or "",
    }
    _cache_put(target_url, "__info__", payload)
    return payload


