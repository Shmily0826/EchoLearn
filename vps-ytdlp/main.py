"""
EchoLearn — server-side YouTube transcript service (FastAPI + yt-dlp)

Runs on a small always-on VPS. yt-dlp does the heavy lifting: it rotates
YouTube client signatures (web / android / tv / ios) and the TVHTML5 client
bypasses YouTube's datacenter-IP bot check, so captions can be fetched
without a residential proxy for the vast majority of videos.

Endpoints
  GET /api/transcript?videoId=<id>&lang=<en>
  GET /api/transcript?url=<any yt-dlp supported url>&lang=<zh-CN>
  GET /api/asr?url=<any yt-dlp supported url>
  GET /api/audio?url=<any yt-dlp supported url>  (mp3 stream for audio-only mode)
  GET /api/info?url=<any yt-dlp supported url>
  GET /api/health

Response shape (matches the EchoLearn web/Worker contract):
  {
    "lines": [{"id": "yt_1", "start": 0.0, "end": 1.23, "text": "..."}, ...],
    "language": "en",
    "isAutoGenerated": false
  }

Environment
  YTDLP_TIMEOUT   subprocess hard timeout in seconds (default 90)
  YTDLP_PROXY     optional upstream proxy passed to yt-dlp (e.g. a residential
                  proxy endpoint). Now used ONLY as a fallback for YouTube when a
                  direct (no-proxy) extraction fails — the TVHTML5 client normally
                  bypasses YouTube's datacenter bot-check without it. Bilibili no
                  longer uses yt-dlp at all: its audio is pulled via the public
                  view + playurl APIs (which answer the VPS IP fine) and the media
                  CDN directly, so the proxy is never touched for Bilibili.
                  NOT used for Groq: Groq works directly from this VPS, and the
                  proxy only adds a flaky hop (Broken pipe).
  YTDLP_API_KEY   if set, /api/transcript and /api/asr require header X-Api-Key to match
  YTDLP_CACHE_TTL in-memory cache TTL in seconds for fetched transcripts (default 3600)
  YTDLP_COOKIES   optional path to a Netscape cookies.txt used for non-YouTube
                  sites. Bilibili only exposes subtitle tracks to logged-in
                  sessions, so a SESSDATA cookie is required there.
  YTDLP_RETRIES   number of yt-dlp subprocess attempts before giving up (default 5).
                  Useful when the residential proxy tunnel drops mid-transfer.
  GROQ_API_KEY    enables /api/asr (Whisper transcription via Groq)
  GROQ_MODEL      Groq speech model (default whisper-large-v3-turbo)
  ASR_MAX_DURATION  reject ASR requests longer than this many seconds (default 1800)

Note on the proxy: YTDLP_PROXY is now a YOUTUBE-ONLY fallback. Bilibili's
*watch page* returns HTTP 412 from both the VPS datacenter IP and the entire
residential-proxy IP pool, so the proxy can't help Bilibili — and Bilibili
doesn't need it anyway, because its JSON APIs (view/playurl) and media CDN are
reachable directly from the VPS. Bilibili audio/ASR/info therefore bypass yt-dlp
entirely and use zero proxy bandwidth. YouTube is tried with NO proxy first
(TVHTML5 client) and only falls back to the proxy if that fails.

Note on Bilibili transcripts: Bilibili gates *subtitle tracks* behind a login,
but audio streams are served to anonymous clients. With a SESSDATA cookie in
YTDLP_COOKIES, the transcript route can fetch the real (or auto) subtitle tracks
— this is the preferred, fast, free path. When that fails (no cookie, or a video
with no subtitle track), the caller falls back to ASR, which sidesteps the login
wall by transcribing the audio instead — no SESSDATA cookie needed for that.
"""

