@app.get("/api/transcript")
def transcript(
    video_id: Optional[str] = Query(default=None, alias="videoId"),
    url: Optional[str] = Query(default=None),
    lang: str = Query("en"),
    request: Request = None,
):
    target = url or video_id
    if not target:
        raise HTTPException(status_code=400, detail="Missing videoId or url")

    is_url = bool(url)
    clean_target = target
    part = None
    if is_url:
        if not _host_allowed(url):
            raise HTTPException(status_code=400, detail="Unsupported url host")
        clean_target, part = _extract_part(url)
    elif not _VIDEO_ID_RE.match(video_id or ""):
        raise HTTPException(status_code=400, detail="Invalid videoId")

    if YTDLP_API_KEY:
        provided = (request.headers.get("X-Api-Key") or "") if request else ""
        if provided != YTDLP_API_KEY:
            raise HTTPException(status_code=401, detail="Unauthorized")

    # Serve from cache (short TTL) to avoid re-hitting YouTube for the same
    # video+lang and to protect the single AWS IP from rate limits.
    cached = _cache_get(target, lang)
    if cached is not None:
        return JSONResponse(cached)

    result = _run_ytdlp(clean_target, lang, is_url=is_url, part=part)

    # Bilibili videos often expose only a Chinese AI subtitle ("ai-zh"). The app
    # is for English learners, so a Chinese-only transcript is useless for
    # vocabulary work. Treat a non-English-only result as "no usable transcript"
    # so the caller falls back to ASR (which returns an English transcript).
    # Videos that DO carry an English/ai-en track are served directly (fast).
    if result and _is_bilibili(clean_target) and not _is_english(result[1]):  # ECHOLEARN_BILI_ENGLISH_GATE
        result = None

    if not result:
        raise HTTPException(
            status_code=404, detail="No transcript available for this video"
        )

    lines, language, is_auto, bvid = result
    payload = {
        "lines": lines,
        "language": language,
        "isAutoGenerated": bool(is_auto),
    }
    if bvid and _is_bilibili(clean_target):
        payload["bvid"] = bvid
    _cache_put(target, lang, payload)
    return JSONResponse(payload)


@app.get("/api/info")
def info(
    url: str = Query(...),
    request: Request = None,
):
    """Lightweight metadata lookup (title / uploader / duration).

    Exists mainly so the Cloudflare Worker doesn't have to call Bilibili
    directly — Bilibili answers Cloudflare Worker egress IPs with HTTP 412,
    while the VPS IP is fine.
    """
    if not _host_allowed(url):
        raise HTTPException(status_code=400, detail="Unsupported url host")

    if YTDLP_API_KEY:
        provided = (request.headers.get("X-Api-Key") or "") if request else ""
        if provided != YTDLP_API_KEY:
            raise HTTPException(status_code=401, detail="Unauthorized")

    payload = _fetch_meta(url)
    # Surface the multi-part (分p) list so the frontend can render a part
    # picker. The view API answers the VPS IP directly (no proxy), and a
    # failure here is non-fatal — the picker just won't appear.
    if _is_bilibili(url):
        bvid = _extract_bvid(url) or payload.get("bvid")
        if bvid:
            parts = _bilibili_parts(bvid)
            if parts:
                payload["partCount"] = parts["partCount"]
                payload["parts"] = parts["parts"]
    return JSONResponse(payload)


@app.get("/api/asr")
def asr(
    url: str = Query(...),
    request: Request = None,
):
    """Transcribe a video's audio with Whisper.

    This is the fallback for videos that expose no subtitle track at all — most
    notably Bilibili, which serves audio anonymously but hides subtitle tracks
    behind a login.
    """
    clean_url, part = _extract_part(url)

    if not GROQ_API_KEY:
        raise HTTPException(status_code=503, detail="ASR not configured (no GROQ_API_KEY)")

    if not _host_allowed(clean_url):
        raise HTTPException(status_code=400, detail="Unsupported url host")

    if YTDLP_API_KEY:
        provided = (request.headers.get("X-Api-Key") or "") if request else ""
        if provided != YTDLP_API_KEY:
            raise HTTPException(status_code=401, detail="Unauthorized")

    # Bilibili: API-direct path (no proxy, no yt-dlp watch-page 412).
    if _is_bilibili(clean_url):
        cached = _cache_get(url, "__asr__")
        if cached is not None:
            return JSONResponse(cached)
        # Do not make ASR depend on a separate metadata lookup. Bilibili's
        # view API can transiently fail even while playurl/CDN audio works;
        # previously that surfaced as 404 "Could not fetch Bilibili info" and
        # prevented the actual API-direct ASR pipeline from running. The ASR
        # path below performs its own view lookup and can retry it. Duration
        # is still enforced when metadata is available, but metadata failure
        # is non-fatal here.
        try:
            duration = int(_fetch_meta(clean_url, part).get("duration") or 0)
        except HTTPException:
            duration = 0
        if duration > ASR_MAX_DURATION:
            raise HTTPException(
                status_code=413,
                detail=(
                    f"Video is {duration // 60} min, over the "
                    f"{ASR_MAX_DURATION // 60} min ASR limit"
                ),
            )
        payload = _bilibili_asr(clean_url, part)
        _cache_put(url, "__asr__", payload)
        return JSONResponse(payload)

    # ASR costs real quota, so a cache hit is worth much more here than on the
    # subtitle routes.
    cached = _cache_get(url, "__asr__")
    if cached is not None:
        return JSONResponse(cached)

    duration = int(_fetch_meta(clean_url, part).get("duration") or 0)
    if duration > ASR_MAX_DURATION:
        raise HTTPException(
            status_code=413,
            detail=(
                f"Video is {duration // 60} min, over the "
                f"{ASR_MAX_DURATION // 60} min ASR limit"
            ),
        )

    with tempfile.TemporaryDirectory() as td:
        audio_path = _download_audio(clean_url, td, part)
        if not audio_path:
            raise HTTPException(status_code=502, detail="Could not download audio")
        payload = _groq_transcribe(audio_path)

    _cache_put(url, "__asr__", payload)
    return JSONResponse(payload)


@app.get("/api/audio")
def audio(
    url: str = Query(...),
    request: Request = None,
):
    """Stream a video's audio track (mp3) for the in-app audio-only player.

    Cached on disk by URL+part so repeat plays are instant. The Cloudflare
    Worker proxies this endpoint to the browser, where a native <audio>
    element plays it and drives transcript sync via its currentTime.
    """
    clean_url, part = _extract_part(url)

    if not _host_allowed(clean_url):
        raise HTTPException(status_code=400, detail="Unsupported url host")

    if YTDLP_API_KEY:
        provided = (request.headers.get("X-Api-Key") or "") if request else ""
        if provided != YTDLP_API_KEY:
            raise HTTPException(status_code=401, detail="Unauthorized")

    path = _audio_cache_path(clean_url, part)
    if _is_bilibili(clean_url):
        # API-direct: CDN download + ffmpeg, no proxy, no yt-dlp watch-page 412.
        if not _cache_valid(path):
            if not _bilibili_audio(clean_url, part, path):
                raise HTTPException(status_code=502, detail="Could not extract audio")
        return FileResponse(
            path,
            media_type="audio/mpeg",
            filename=os.path.basename(path),
            content_disposition_type="inline",
            headers={"Cache-Control": "public, max-age=86400, immutable"},
        )

    if not (os.path.exists(path) and os.path.getsize(path) > 0):
        path = _extract_playback_audio_dedup(clean_url, part)
    if not path:
        raise HTTPException(status_code=502, detail="Could not extract audio")

    return FileResponse(
        path,
        media_type="audio/mpeg",
        filename=os.path.basename(path),
        content_disposition_type="inline",
        headers={"Cache-Control": "public, max-age=86400, immutable"},
    )


